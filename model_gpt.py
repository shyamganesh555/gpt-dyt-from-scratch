def get_batch(split):
  data = train_data if split == 'train' else val_data
  ix = torch.randint(len(data) - block_size - 1, (batch_size,))
  x = torch.stack([data[i:i+block_size] for i in ix])
  y = torch.stack([data[i+1:i+block_size+1] for i in ix])
  x, y = x.to(device), y.to(device)
  return x, y

# Dynamic Tanh
class Dynamic_Tanh(nn.Module):
  def __init__(self, n_dim, alpha_init = 0.5, bias = True):
    super().__init__()
    self.weight = nn.Parameter(torch.ones(n_dim))
    self.bias = nn.Parameter(torch.zeros(n_dim)) if bias else None
    self.alpha = nn.Parameter(torch.ones(1) * alpha_init)

  def forward(self, x):
    x = torch.tanh(self.alpha * x)
    if self.bias is not None:
      return self.weight * x + self.bias
    return self.weight * x

# Multihead Attention
class MultiheadAttention(nn.Module):
  def __init__(self, n_embd, n_heads, block_size, dropout = dropout):
    super().__init__()

    assert n_embd % n_heads == 0

    self.n_heads = n_heads
    self.n_embd = n_embd

    self.head_size = n_embd // n_heads
    self.tril = torch.tril(torch.ones((block_size, block_size)))

    self.qkv = nn.Linear(n_embd, 3 * n_embd, bias = False)
    self.proj = nn.Linear(n_embd, n_embd)

    self.dropout = nn.Dropout(dropout)

  def forward(self, x):
    B, T, C = x.shape
    q, k, v = self.qkv(x).split(self.n_embd, dim = -1)

    q = q.view(B, T, self.n_heads, self.head_size).transpose(1, 2)
    k = k.view(B, T, self.n_heads, self.head_size).transpose(1, 2)
    v = v.view(B, T, self.n_heads, self.head_size).transpose(1, 2)

    wei = q @ k.transpose(-2, -1) / math.sqrt(self.head_size)
    wei = wei.masked_fill(self.tril[:T, :T].to(x.device) == 0, float('-inf'))
    wei = F.softmax(wei, dim = -1)
    wei = self.dropout(wei)

    out = wei @ v
    out = out.transpose(1, 2).contiguous().view(B, T, C)
    out = self.proj(out)

    return out

# Feed Forward Neural Network
class FeedForward(nn.Module):
  def __init__(self,n_embd):
    super().__init__()
    self.net = nn.Sequential(
        nn.Linear(n_embd, 4 * n_embd),
        nn.GELU(),
        nn.Linear(4 * n_embd, n_embd)
    )

  def forward(self, x):
   return self.net(x)

class Block(nn.Module):
  def __init__(self, n_embd, n_head, block_size):
    super().__init__()
    self.dyt1 = Dynamic_Tanh(n_embd)
    self.mha = MultiheadAttention(n_embd, n_head, block_size, dropout = dropout)
    self.dyt2 = Dynamic_Tanh(n_embd)
    self.ffnn = FeedForward(n_embd)

  def forward(self, x):
    x = x + self.mha(self.dyt1(x))
    x = x + self.ffnn(self.dyt2(x))

    return x

class GPTLanguageModel(nn.Module):
  def __init__(self, n_embd, n_heads, vocab_size):
    super().__init__()
    self.block_size = block_size

    self.token_embedding_table = nn.Embedding(vocab_size, n_embd)

    self.position_embedding_table = nn.Embedding(block_size, n_embd)

    self.blocks = nn.Sequential(*[Block(n_embd, n_heads, block_size) for _ in range(n_layers)])

    self.final_norm = Dynamic_Tanh(n_embd)

    self.lm_head = nn.Linear(n_embd, vocab_size)

  def forward(self, idx, targets = None):
    B, T = idx.shape

    assert T <= self.block_size

    token_embd = self.token_embedding_table(idx)
    position_embd = self.position_embedding_table(torch.arange(T, dtype = torch.long, device = idx.device))

    x = self.blocks(token_embd + position_embd)
    x = self.final_norm(x)

    logits = self.lm_head(x)

    if targets is None:
      return logits, None
    else:
      B, T, C = logits.shape
      targets = targets.view(B * T)
      logits = logits.view(B * T, C)

      loss = F.cross_entropy(logits, targets)
    return logits, loss

  def generate(self, idx, max_new_tokens):
    for _ in range(max_new_tokens):
      id_cond = idx[:, -self.block_size:]

      logits, loss = self(id_cond)

      logits = logits[:, -1, :]

      probs = F.softmax(logits, dim = -1)

      idx_next = torch.multinomial(probs, 1)

      idx = torch.cat((idx, idx_next), dim = 1)

    return idx


model_GPT = GPTLanguageModel(n_embd, n_heads, vocab_size).to(device)

# Adam Optimizer
optim = torch.optim.AdamW(model_GPT.parameters(), lr = learning_rate)

@torch.no_grad()
def estimate_loss():
    out = {}
    model_GPT.eval()
    for split in ['train', 'val']:
        losses = torch.zeros(50)
        for k in range(50):
            X, Y = get_batch(split)
            _, loss = model_GPT(X, Y)
            losses[k] = loss.item()
        out[split] = losses.mean().item()
    model_GPT.train()
    return out

